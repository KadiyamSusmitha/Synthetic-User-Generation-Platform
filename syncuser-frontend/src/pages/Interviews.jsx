  async function handleViewInterview(interviewId) {
    try {
      setOpeningInterviewId(interviewId);
      setError("");

      const conversation = await getInterview(interviewId);

      let interviewResult = null;

      if (conversation?.interview?.status === "Completed") {
        try {
          interviewResult = await getInterviewResult(interviewId);
        } catch {
          interviewResult = null;
        }
      }

      openedInterviewRef.current = {
        interview: conversation.interview,
        messages: normalizeMessages(conversation.messages),
        result: interviewResult,
      };

      setSelectedExperimentId(
        String(conversation.interview.experiment_id),
      );
      setSelectedPersonaId(conversation.interview.persona_id);
      setMessages(normalizeMessages(conversation.messages));
      setInterview(conversation.interview);
      setResult(interviewResult);
      setInterviewSaved(Boolean(conversation.interview?.is_saved));
      setPersonasCollapsed(false);
      setResultOpen(false);
      setHeaderMenuOpen(false);
      setWorkspaceReturnMode(interviewListMode);
      setShowInterviewList(false);
    } catch (err) {
      toast.error(
        err?.message || "Failed to open the interview.",
      );
    } finally {
      setOpeningInterviewId(null);
    }
  }

  async function handleDeleteInterview(interviewId) {
    const confirmed = window.confirm(
      "Are you sure you want to delete this interview? This action cannot be undone.",
    );

    if (!confirmed) {
      return;
    }

    try {
      setDeletingInterviewId(interviewId);

      await deleteInterview(interviewId);

      setInterviews((current) =>
        current.filter((item) => item.id !== interviewId),
      );

      if (interview?.id === interviewId) {
        setInterview(null);
        setMessages([]);
        setResult(null);
        setInterviewSaved(false);
      }

      toast.success("Interview deleted.");
    } catch (err) {
      toast.error(
        err?.message || "Failed to delete interview.",
      );
    } finally {
      setDeletingInterviewId(null);
    }
  }

