/*
 * Backend timestamps can sometimes arrive without an explicit
 * timezone. The backend stores timestamps as UTC, so when no
 * timezone is present we treat the value as UTC before converting
 * it to the user's local time.
 */
function parseMessageDate(value) {
  if (!value) {
    return null;
  }

  if (value instanceof Date) {
    return value;
  }

  const raw = String(value).trim();

  if (!raw) {
    return null;
  }

  const hasTimezone =
    /(?:Z|[+-]\d{2}:?\d{2})$/i.test(raw);

  const normalized = hasTimezone ? raw : `${raw}Z`;

  const date = new Date(normalized);

  return Number.isNaN(date.getTime()) ? null : date;
}

function formatMessageTime(value) {
  const date = parseMessageDate(value);

  if (!date) {
    return "";
  }

  return date.toLocaleTimeString([], {
    hour: "numeric",
    minute: "2-digit",
  });
}

/*
 * Normal interviewer questions:
 *   questionType = "primary"
 *
 * Follow-up questions:
 *   questionType = "follow_up"
 *
 * The override is applied only to the latest interviewer
 * message generated by the current action.
 */
function normalizeMessages(messages = [], latestQuestionType = null) {
  const normalized = messages.map((message) => ({
    id: message.id,
    sender: message.role === "interviewer" ? "ai" : "persona",
    text: message.message,
    time: formatMessageTime(message.created_at),
    questionType: message.question_type || null,
  }));

  if (latestQuestionType) {
    for (let index = normalized.length - 1; index >= 0; index -= 1) {
      if (normalized[index].sender === "ai") {
        normalized[index] = {
          ...normalized[index],
          questionType: latestQuestionType,
        };

        break;
      }
    }
  }

  return normalized;
}

/*
 * Count actual interviewer prompts shown in the conversation.
 *
 * Generated:
 *   Every AI interviewer message.
 *
 * Follow-ups:
 *   AI interviewer messages explicitly marked as follow_up.
 *
 * Questions explored:
 *   Generated questions excluding follow-ups.
 */
function getInterviewProgress(messages = []) {
  const interviewerMessages = messages.filter(
    (message) => message.sender === "ai",
  );

  const followUps = interviewerMessages.filter(
    (message) => message.questionType === "follow_up",
  ).length;

  const generated = interviewerMessages.length;

  const explored = Math.max(0, generated - followUps);

  return {
    generated,
    explored,
    followUps,
  };
}

