    const query = interviewListSearch.trim().toLowerCase();

    return interviews.filter((item) => {
      if (
        interviewListMode === "saved" &&
        !item.is_saved
      ) {
        return false;
      }

      if (
        interviewStatusFilter !== "All" &&
        item.status !== interviewStatusFilter
      ) {
        return false;
      }

      if (!query) {
        return true;
      }

      const experimentName =
        experiments.find(
          (experiment) =>
            Number(experiment.id) === Number(item.experiment_id),
        )?.name || "";

      const personaName =
        interviewPersonaNames[item.persona_id] || "";

      return [
        item.id,
        experimentName,
        personaName,
        item.status,
      ]
        .join(" ")
        .toLowerCase()
        .includes(query);
    });
